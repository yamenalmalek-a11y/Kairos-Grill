export function formatEuro(amount: number): string {
  return `${amount.toFixed(2).replace('.', ',')} €`;
}

export function getEntryUnitPrice(entry: Pick<CartEntry, 'dish' | 'variant'>): number {
  return entry.variant ? entry.variant.price : entry.dish.price;
}

export interface CartTotals {
  foodNet: number;
  drinksNet: number;
  subtotal: number;
  foodTax: number;
  drinksTax: number;
  totalTax: number;
  deliveryFee: number;
  total: number;
}

export function calculateCartTotals(
  items: CartEntry[],
  orderMode: 'delivery' | 'pickup'
): CartTotals {
  let foodNet = 0;
  let drinksNet = 0;

  for (const entry of items) {
    const line = getEntryUnitPrice(entry) * entry.quantity;
    if (entry.dish.taxRate === 0.19) {
      drinksNet += line;
    } else {
      foodNet += line;
    }
  }

  const subtotal = +(foodNet + drinksNet).toFixed(2);
  const foodTax = +(foodNet * 0.07).toFixed(2);
  const drinksTax = +(drinksNet * 0.19).toFixed(2);
  const totalTax = +(foodTax + drinksTax).toFixed(2);

  const deliveryFee =
    orderMode === 'pickup' || subtotal === 0 || subtotal >= KAIROS_INFO.freeDeliveryThreshold
      ? 0
      : KAIROS_INFO.deliveryFee;

  const total = +(subtotal + totalTax + deliveryFee).toFixed(2);

  return {
    foodNet,
    drinksNet,
    subtotal,
    foodTax,
    drinksTax,
    totalTax,
    deliveryFee,
    total,
  };
}

export interface WhatsAppOrderPayload {
  orderNumber: string;
  customerName: string;
  customerPhone: string;
  orderMode: 'delivery' | 'pickup';
  address: string;
  gpsCoords?: { lat: number; lng: number } | null;
  paymentMethod: 'cash' | 'payment_link';
  paymentLink?: string;
  notes?: string;
  items: CartEntry[];
  totals: CartTotals;
  lang: 'ar' | 'de';
}

export function buildWhatsAppOrderText(payload: WhatsAppOrderPayload): string {
  const itemLines = payload.items
    .map((entry, index) => {
      const unitPrice = getEntryUnitPrice(entry);
      const taxLabel = entry.dish.taxRate === 0.19 ? '19%' : '7%';
      const numPrefix = entry.dish.itemNumber ? `#${entry.dish.itemNumber} ` : '';
      const variantAr = entry.variant ? ` (${entry.variant.labelAr})` : '';
      const variantDe = entry.variant ? ` (${entry.variant.labelDe})` : '';
      return `${index + 1}. ${numPrefix}*${entry.dish.nameAr}${variantAr}* (${entry.dish.nameDe}${variantDe}) [${taxLabel}]\n   ${entry.quantity} × ${formatEuro(unitPrice)} = *${formatEuro(unitPrice * entry.quantity)}*`;
    })
    .join('\n');

  const locationLine =
    payload.orderMode === 'pickup'
      ? `استلام من المطعم (${KAIROS_INFO.address})`
      : payload.address;

  const mapsLine = payload.gpsCoords
    ? `\n📍 رابط الموقع (Google Maps): https://maps.google.com/?q=${payload.gpsCoords.lat.toFixed(6)},${payload.gpsCoords.lng.toFixed(6)}`
    : '';

  const paymentMethodLabel =
    payload.paymentMethod === 'payment_link'
      ? 'الدفع الإلكتروني عبر الرابط (Online)'
      : 'نقداً عند الاستلام (Barzahlung)';

  const paymentLinkLine =
    payload.paymentLink && payload.paymentLink.trim()
      ? `\n💳 رابط الدفع:\n${payload.paymentLink.trim()}`
      : '';

  const notesLine = payload.notes?.trim() ? `\n📝 ملاحظات: ${payload.notes.trim()}` : '';

  const deliveryLine =
    payload.orderMode === 'pickup'
      ? 'استلام من المطعم (0,00 €)'
      : payload.totals.deliveryFee === 0
        ? 'مجاني (0,00 €)'
        : formatEuro(payload.totals.deliveryFee);

  const taxLines: string[] = [];
  if (payload.totals.foodTax > 0) {
    taxLines.push(`ضريبة الأكل (7% MwSt.): ${formatEuro(payload.totals.foodTax)}`);
  }
  if (payload.totals.drinksTax > 0) {
    taxLines.push(`ضريبة المشروبات (19% MwSt.): ${formatEuro(payload.totals.drinksTax)}`);
  }

  return [
    `🧾 *فاتورة طلب جديدة — Kairos Grill*`,
    `رقم الطلب: *#${payload.orderNumber}*`,
    `━━━━━━━━━━━━━━━━━━━━`,
    `👤 *الاسم:* ${payload.customerName}`,
    `📞 *الهاتف:* ${payload.customerPhone}`,
    `📍 *الموقع / العنوان:* ${locationLine}${mapsLine}`,
    ``,
    `📋 *تفاصيل الفاتورة:*`,
    itemLines,
    `━━━━━━━━━━━━━━━━━━━━`,
    `المجموع الفرعي (صافي): ${formatEuro(payload.totals.subtotal)}`,
    ...taxLines,
    `رسوم التوصيل: ${deliveryLine}`,
    `💰 *المجموع النهائي (شامل الضريبة): ${formatEuro(payload.totals.total)}*`,
    ``,
    `💳 *طريقة الدفع:* ${paymentMethodLabel}${paymentLinkLine}${notesLine}`,
  ].join('\n');
}

export function buildWhatsAppUrl(message: string): string {
  return `https://wa.me/${KAIROS_INFO.whatsappInternational}?text=${encodeURIComponent(message)}`;
}
